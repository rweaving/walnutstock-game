const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.resolve(__dirname, '..', 'assets', 'data');

const RATE = 0.55; // clockMinutesPerRealSecond: 1 real second = 0.55 in-game minutes (~38 min real-time per full day)
const r2 = (n) => Math.round(n * 100) / 100;

function makeTrack(spec) {
  const endMinute = r2(spec.startMinute + spec.durationSeconds * RATE);
  return {
    trackNumber: spec.trackNumber,
    id: spec.id,
    title: spec.title,
    artist: spec.artist,
    day: spec.day,
    startMinute: r2(spec.startMinute),
    endMinute,
    durationSeconds: spec.durationSeconds,
    stageId: spec.stageId,
    assetPath: spec.assetPath,
    bundledInCore: Boolean(spec.bundledInCore),
    isPaBroadcast: Boolean(spec.isPaBroadcast),
    isBonusStem: Boolean(spec.isBonusStem),
    worldEvent: spec.worldEvent ?? null,
    reactiveCues: spec.reactiveCues ?? [],
    subtitle: spec.subtitle ?? null,
  };
}

